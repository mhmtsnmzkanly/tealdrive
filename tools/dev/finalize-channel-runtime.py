#!/usr/bin/env python3
"""Deterministic JS lifecycle fix for wasm-bindgen0.2.122; no crypto changes.
A module has one WASM instance even across distinct concurrent loader functions.
"""
from pathlib import Path
path=Path(__file__).resolve().parents[2]/'src/ui/sdk/noise/noise.js'
text=path.read_text()
old='async function __wbg_init(module_or_path) {'
if text.count(old)!=1:raise SystemExit('Unexpected wasm-bindgen runtime shape')
text=text.replace(old,'let pendingNoiseInitialization;\nasync function __wbg_init_once(module_or_path) {',1)
old='function initSync(module) {\n    if (wasm !== undefined) return wasm;'
if text.count(old)!=1:raise SystemExit('Unexpected synchronous initializer shape')
text=text.replace(old,old+"\n    if (pendingNoiseInitialization) throw new Error('Noise async initialization is in progress');",1)
text+='''\n// Tealdrive lifecycle guard; regenerated by tools/dev/build-channel.sh.\nfunction __wbg_init(module_or_path) {\n    if (wasm !== undefined) return Promise.resolve(wasm);\n    if (!pendingNoiseInitialization) {\n        pendingNoiseInitialization = __wbg_init_once(module_or_path).catch(error => {\n            pendingNoiseInitialization = undefined;\n            throw error;\n        });\n    }\n    return pendingNoiseInitialization;\n}\n'''
path.write_text(text)
